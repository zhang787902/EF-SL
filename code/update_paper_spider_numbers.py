# -*- coding: utf-8 -*-
"""Spider 修正数字批量替换 paper.md（一次性脚本，改完可删）"""
import sys
sys.stdout.reconfigure(errors='replace')

P = "paper.md"
s = open(P, encoding='utf-8').read()

log = []

def rep(old, new):
    global s
    n = s.count(old)
    if n:
        s = s.replace(old, new)
    log.append((old, new, n))
    return n

# ============ 1. Spider 准确率绝对值 ============
for old, new in [
    ("67.50%", "68.76%"),
    ("67.50", "68.76"),
    ("67.5%", "68.8%"),
    ("67.5", "68.8"),
    ("67.60", "69.05"),
    ("67.6", "69.1"),
    ("62.86", "63.64"),
    ("62.9", "63.6"),
    ("64.51", "65.67"),
    ("64.5", "65.7"),
    ("71.66", "72.82"),
    ("71.7", "72.8"),
]:
    rep(old, new)

# ============ 2. Delta（含 − 与 - 两种符号） ============
for old, new in [
    ("-4.64", "-5.13"),
    ("\u22124.64", "\u22125.13"),
    ("-3.00", "-3.09"),
    ("\u22123.00", "\u22123.09"),
    ("+0.10", "+0.29"),
    ("+4.16", "+4.06"),
]:
    rep(old, new)

# ============ 3. p 值 ============
for old, new in [
    ("8.0\u00d710\u207b\u2076", "1.27\u00d710\u207b\u2076"),
    ("8\u00d710\u207b\u2076", "1.27\u00d710\u207b\u2076"),
    ("2.0\u00d710\u207b\u2074", "1.0\u00d710\u207b\u2074"),
    ("2\u00d710\u207b\u2074", "1\u00d710\u207b\u2074"),
    ("1.2\u00d710\u207b\u2075", "2.64\u00d710\u207b\u2075"),
    ("1\u00d710\u207b\u2075", "2.64\u00d710\u207b\u2075"),
    ("1.000", "0.711"),
]:
    rep(old, new)

# ============ 4. Fix/Break/Net ============
rep("| 69 | 26 |", "| 70 | 28 |")
rep("| 15 | 14 | +1 |", "| 16 | 13 | +3 |")
rep("Net=+1（15 vs 14）", "Net=+3（16 vs 13）")
rep("Net=+1 的安全表现", "Net=+3 的安全表现")
rep("26 个", "28 个")

# ============ 5. 难度梯度文本 ============
rep("Easy \u22120.3% \u2192 Extra Hard \u221212.2%", "Easy +0.3% \u2192 Extra Hard \u221213.5%")
rep("从 Easy 的 \u22120.3% 恶化至 Extra Hard 的 \u221212.2%", "从 Easy 的 +0.3% 恶化至 Extra Hard 的 \u221213.5%")
rep("-12.2%", "-13.5%")
rep("\u221212.2%", "\u221213.5%")
rep("LLM-SL 从 Easy 的 -0.5% 恶化至", "LLM-SL 从 Easy 的 -0.3% 恶化至")

# ============ 6. 发现2/发现3 文本 ============
rep("55.1%（+0.9% vs Baseline）", "57.6%（+1.3% vs Baseline）")
rep("分别跌至 45.8% 和 50.2%", "分别跌至 46.4% 和 51.7%")
rep("Oracle SL 揭示了 4.16% 的理论上界", "Oracle SL 揭示了 4.06% 的理论上界")
rep("（Easy +2.2%，Medium +6.0%，Hard +5.0%，Extra Hard +4.1%）", "（Easy +2.4%，Medium +6.0%，Hard +3.8%，Extra Hard +6.8%）")
rep("仍有 4.06% 的差距", "仍有 3.77% 的差距")

# ============ 7. Table 3 (难度分层) 整块 ============
