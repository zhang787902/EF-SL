rep(t9_old, t9_new)

# ============ 输出报告 ============
print("=== 替换报告 ===")
zero = []
for old, new, n in log:
    flag = "" if n else "  <<< 未命中!"
    if n == 0:
        zero.append(old)
    print(f"{n:3d}x  {old!r}  ->  {new!r}{flag}")

print()
print("未命中的替换（需人工检查）:", zero if zero else "无")

# ============ 落盘 ============
open(P, "w", encoding='utf-8').write(s)
print("\n已写回 paper.md")